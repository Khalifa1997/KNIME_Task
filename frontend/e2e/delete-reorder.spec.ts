import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('moves stable Steps, swaps coordinates, runs in Chain order, and deletes with node focus', async ({ page }) => {
  await page.goto('/')
  const palette = page.getByRole('region', { name: 'Add Step' })
  const live = page.locator('#chain-announcement')
  await expect(live).toHaveAttribute('aria-live', 'polite')
  await expect(live).toHaveAttribute('aria-atomic', 'true')
  await page.getByRole('textbox', { name: 'Input text' }).fill('a')
  await palette.getByRole('button', { name: 'Append', exact: true }).click()
  const append = page.getByRole('group', { name: 'Step 1: Append', exact: true })
  await append.getByRole('textbox').fill('b')
  await palette.getByRole('button', { name: 'Uppercase', exact: true }).click()
  const upper = page.getByRole('group', { name: 'Step 2: Uppercase', exact: true })
  await expect(append.getByRole('button', { name: /earlier/ })).toBeDisabled()
  await expect(upper.getByRole('button', { name: /later/ })).toBeDisabled()
  await page.getByRole('button', { name: 'Run', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Up to date')
  await expect(page.getByRole('group', { name: 'Output', exact: true })).toContainText('AB')
  // Arrow movement is positional only and survives the next projection.
  await upper.focus()
  await upper.press('Enter')
  const before = await upper.getAttribute('style')
  await upper.press('ArrowDown')
  await expect(upper).not.toHaveAttribute('style', before!)
  const appendStyle = await append.getAttribute('style')
  const upperStyle = await upper.getAttribute('style')
  await expect(live).toBeEmpty()
  await append.getByRole('button', { name: /later/ }).click()
  const movedAppend = page.getByRole('group', { name: 'Step 2: Append', exact: true })
  const movedUpper = page.getByRole('group', { name: 'Step 1: Uppercase', exact: true })
  await expect(live).toHaveText('Moved Append to position 2 of 2.')
  await expect(movedAppend).toBeFocused()
  await expect(movedAppend).toHaveAttribute('style', upperStyle!)
  await expect(movedUpper).toHaveAttribute('style', appendStyle!)
  await expect(movedAppend.getByRole('textbox')).toHaveValue('b')
  await expect(page.getByRole('status')).toHaveText('Changed since the last run')
  await movedAppend.getByRole('button', { name: /earlier/ }).click()
  await expect(page.getByRole('status')).toHaveText('Up to date')
  await append.getByRole('button', { name: /later/ }).click()
  await page.getByRole('button', { name: 'Run', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Up to date')
  await expect(page.getByRole('group', { name: 'Output', exact: true })).toContainText('Ab')
  await movedAppend.getByRole('button', { name: /Delete/ }).click()
  await expect(movedUpper).toBeFocused()
  await expect(live).toHaveText('Deleted Append. Step 1: Uppercase now leads into Output.')
  await expect(page.getByRole('img', { name: 'Step 1 to Output', exact: true })).toBeAttached()
  await movedUpper.press('Backspace')
  await expect(movedUpper).toBeAttached()
  await movedUpper.press('Delete')
  await expect(page.getByRole('group', { name: 'Input text', exact: true })).toBeFocused()
  await expect(live).toHaveText('Deleted Uppercase. Input text now leads into Output.')
  await expect(page.locator('.vue-flow__node-step')).toHaveCount(0)
})

test('deletes only focused wrappers, preserves native Field keys, and exposes accessible controls', async ({ page }, testInfo) => {
  await page.goto('/')
  const palette = page.getByRole('region', { name: 'Add Step' })
  for (const name of ['Uppercase', 'Replace', 'Lowercase']) {
    await palette.getByRole('button', { name, exact: true }).click()
  }
  await expect(page.getByRole('group', { name: 'Step 3: Lowercase', exact: true })).toBeFocused()
  const replace = page.getByRole('group', { name: 'Step 2: Replace', exact: true })
  const search = replace.getByRole('textbox', { name: 'Search', exact: true })
  await search.fill('abc')
  await search.press('Home')
  await search.press('Delete')
  await expect(search).toHaveValue('bc')
  await search.press('End')
  await search.press('Backspace')
  await expect(search).toHaveValue('b')
  await palette.getByRole('button', { name: 'Uppercase', exact: true }).focus()
  await page.keyboard.press('Delete')
  await expect(page.locator('.vue-flow__node-step')).toHaveCount(3)
  const earlier = replace.getByRole('button', { name: /earlier/ })
  await expect(earlier).toHaveText(testInfo.project.name === 'phone' ? '↑' : '←')
  await earlier.focus()
  const position = await replace.getAttribute('style')
  await earlier.press('ArrowRight')
  await expect(replace).toHaveAttribute('style', position!)
  await replace.getByRole('button', { name: /Delete/ }).click()
  await expect(page.getByRole('group', { name: 'Step 1: Uppercase', exact: true })).toBeFocused()
  await expect(page.locator('#chain-announcement')).toHaveText('Deleted Replace. Step 1: Uppercase now leads into Step 2: Lowercase.')
  const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze()
  expect(results.violations).toEqual([])
})

test('reannounces equal deletions and leaves endpoint wrappers intact', async ({ page }) => {
  await page.goto('/')
  const add = page.getByRole('region', { name: 'Add Step' }).getByRole('button', { name: 'Uppercase', exact: true })
  const live = page.locator('#chain-announcement')
  await add.click()
  await page.getByRole('button', { name: 'Delete Step 1: Uppercase' }).click()
  await expect(live).toHaveText('Deleted Uppercase. Input text now leads into Output.')
  await page.evaluate(() => {
    const region = document.querySelector('#chain-announcement')!
    const changes: string[] = []
    Object.assign(window, { announcementChanges: changes })
    new MutationObserver(() => changes.push(region.textContent ?? '')).observe(region, { childList: true, characterData: true, subtree: true })
  })
  await add.click()
  const step = page.getByRole('group', { name: 'Step 1: Uppercase', exact: true })
  await expect(step.getByRole('button', { name: /earlier/ })).toBeDisabled()
  await expect(step.getByRole('button', { name: /later/ })).toBeDisabled()
  await step.getByRole('button', { name: /Delete/ }).click()
  await expect.poll(() => page.evaluate(() => (window as unknown as { announcementChanges: string[] }).announcementChanges)).toEqual(['', 'Deleted Uppercase. Input text now leads into Output.'])
  const input = page.getByRole('group', { name: 'Input text', exact: true })
  await input.press('Delete')
  await expect(input).toBeAttached()
  const output = page.getByRole('group', { name: 'Output', exact: true })
  await output.focus()
  await output.press('Delete')
  await expect(output).toBeAttached()
})

test('swaps a mouse-dragged position with a fallback slot and preserves Chain Tab order', async ({ page }) => {
  await page.goto('/')
  const palette = page.getByRole('region', { name: 'Add Step' })
  await palette.getByRole('button', { name: 'Uppercase', exact: true }).click()
  await palette.getByRole('button', { name: 'Lowercase', exact: true }).click()
  await page.getByRole('button', { name: 'Fit View' }).click()
  const upper = page.getByRole('group', { name: 'Step 1: Uppercase', exact: true })
  const beforeDrag = await upper.getAttribute('style')
  const title = upper.getByRole('heading')
  const box = await title.boundingBox()
  expect(box).not.toBeNull()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
  await page.mouse.down()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2 + 80, { steps: 8 })
  await page.mouse.up()
  await expect(upper).not.toHaveAttribute('style', beforeDrag!)
  const dragged = await upper.getAttribute('style')
  const lower = page.getByRole('group', { name: 'Step 2: Lowercase', exact: true })
  const fallback = await lower.getAttribute('style')
  await upper.getByRole('button', { name: /later/ }).click()
  const movedUpper = page.getByRole('group', { name: 'Step 2: Uppercase', exact: true })
  const movedLower = page.getByRole('group', { name: 'Step 1: Lowercase', exact: true })
  // Selection changes z-index, so compare rendered translations only.
  const translation = (style: string) => style.match(/translate\([^)]+\)/)?.[0]
  await expect.poll(async () => translation((await movedUpper.getAttribute('style'))!)).toBe(translation(fallback!))
  await expect.poll(async () => translation((await movedLower.getAttribute('style'))!)).toBe(translation(dragged!))
  await expect(page.locator('.vue-flow__node-step h2')).toHaveText(['1Step 1: Lowercase', '2Step 2: Uppercase'])
  await movedLower.getByRole('button', { name: /Delete/ }).focus()
  await page.keyboard.press('Tab')
  await expect(movedUpper).toBeFocused()
})
