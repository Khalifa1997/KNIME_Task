import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import problem from '../../contract/post-chain-run.two-broken-steps.422.json' with { type: 'json' }
import overflow from '../../contract/post-chain-run.result-too-long.422.json' with { type: 'json' }

const tags = ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22a', 'wcag22aa']

test('attaches all Step errors, clears previews, preserves focus and keeps a fresh Step clean', async ({ page }) => {
  const requests: string[] = []
  page.on('request', (request) => {
    if (request.method() === 'POST' && request.url().endsWith('/api/chain/run')) requests.push(request.url())
  })
  await page.goto('/')
  const add = page.getByRole('region', { name: 'Add Step' }).getByRole('button', { name: 'Replace', exact: true })
  const first = page.getByRole('group', { name: 'Step 1: Replace' })
  const second = page.getByRole('group', { name: 'Step 2: Replace' })
  const output = page.getByRole('group', { name: 'Output' })
  await page.getByRole('textbox', { name: 'Input text' }).fill('a')
  await add.click()
  await expect(first.getByRole('textbox', { name: 'Search' })).toBeFocused()
  await first.getByRole('textbox', { name: 'Search' }).fill('a')
  await first.getByRole('textbox', { name: 'Replacement' }).fill('b')
  await add.click()
  await expect(second.getByRole('textbox', { name: 'Search' })).toBeFocused()
  await second.getByRole('textbox', { name: 'Search' }).fill('b')
  await second.getByRole('textbox', { name: 'Replacement' }).fill('c')
  await second.getByRole('textbox', { name: 'Search' }).press('Control+Enter')
  await expect(page.getByRole('status')).toHaveText('Up to date')
  await expect(first.locator('.node__result')).toHaveText('b')
  await expect(second.locator('.node__result')).toHaveText('c')
  await expect(output.locator('.node__result')).toHaveText('c')
  await first.getByRole('textbox', { name: 'Search' }).fill('')
  const focused = second.getByRole('textbox', { name: 'Search' })
  await focused.fill('')
  await expect(page.locator('.node--invalid')).toHaveCount(0)
  const responsePromise = page.waitForResponse((response) => response.url().endsWith('/api/chain/run') && response.status() === 422)
  await focused.press('Control+Enter')
  const response = await responsePromise
  const ids = response.request().postDataJSON().steps.map((step: { id: string }) => step.id)
  expect(await response.json()).toEqual({ ...problem, errors: problem.errors.map((error, index) => ({ ...error, stepId: ids[index] })) })
  await expect(page.getByRole('status')).toHaveText(problem.detail)
  await expect(focused).toBeFocused()
  await expect(page.locator('.node--invalid')).toHaveCount(2)
  for (const step of [first, second]) {
    const search = step.getByRole('textbox', { name: 'Search' })
    await expect(search).toHaveAttribute('aria-invalid', 'true')
    await expect(search).toHaveAccessibleDescription(problem.errors[0]!.detail)
    await expect(step.locator('.node__result')).toHaveText('Run to see it')
    await expect(step.locator('.node')).toHaveCSS('border-top-color', 'rgb(255, 214, 10)')
    await expect(step.locator('.node')).toHaveCSS('box-shadow', /rgb\(229, 72, 77\) 0px 0px 0px 2px/)
  }
  await expect(output).toContainText('Press Run to see the Output.')
  expect(requests).toHaveLength(2)
  expect((await new AxeBuilder({ page }).withTags(tags).analyze()).violations).toEqual([])
  await add.click()
  const third = page.getByRole('group', { name: 'Step 3: Replace' })
  await expect(third.getByRole('textbox', { name: 'Search' })).toBeFocused()
  await expect(third.locator('.node')).not.toHaveClass(/node--invalid/)
  await expect(third.getByRole('textbox', { name: 'Search' })).not.toHaveAttribute('aria-invalid')
  await third.getByRole('textbox', { name: 'Search' }).press('Control+Enter')
  await expect(page.getByRole('status')).toHaveText('3 problems stop the Chain from running.')
  await expect(page.locator('.node--invalid')).toHaveCount(3)
  for (const step of [first, second, third]) await step.getByRole('textbox', { name: 'Search' }).fill('a')
  await third.getByRole('textbox', { name: 'Search' }).press('Control+Enter')
  await expect(page.getByRole('status')).toHaveText('Up to date')
  await expect(page.locator('.node--invalid')).toHaveCount(0)
  await expect(page.locator('[aria-invalid="true"]')).toHaveCount(0)
  expect(requests).toHaveLength(4)
})

test('renders Input errors without losing the count description or truncating text', async ({ page }) => {
  await page.goto('/')
  const input = page.getByRole('textbox', { name: 'Input text' })
  await input.fill('x'.repeat(3001))
  await input.press('Control+Enter')
  await expect(page.getByRole('status')).toHaveText('1 problem stops the Chain from running.')
  await expect(input).toHaveValue('x'.repeat(3001))
  await expect(input).toBeFocused()
  await expect(input).toHaveAttribute('aria-invalid', 'true')
  await expect(input).toHaveAccessibleDescription('3,001 / 3,000 Input text is longer than 3,000 characters.')
  await expect(page.locator('.node--invalid')).toHaveCount(1)
  expect((await new AxeBuilder({ page }).withTags(tags).analyze()).violations).toEqual([])
})

test('renders a runtime whole-Step error at the top without exposing partial results', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('textbox', { name: 'Input text' }).fill('x'.repeat(3000))
  await page.getByRole('region', { name: 'Add Step' }).getByRole('button', { name: 'Append' }).click()
  const step = page.getByRole('group', { name: 'Step 1: Append' })
  const text = step.getByRole('textbox', { name: 'Text' })
  await expect(text).toBeFocused()
  await text.fill('y')
  await text.press('Control+Enter')
  await expect(page.getByRole('status')).toHaveText(overflow.detail)
  await expect(step.locator('.node > .error-messages')).toHaveText(overflow.errors[0]!.detail)
  await expect(text).not.toHaveAttribute('aria-invalid')
  await expect(text).toBeFocused()
  await expect(step.locator('.node__result')).toHaveText('Run to see it')
  await expect(page.getByRole('group', { name: 'Output' })).toContainText('Press Run to see the Output.')
})
